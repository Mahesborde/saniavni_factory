import "dotenv/config";
import pg from "pg";

type FarmerRecord = {
  id: number | string;
  name: string;
  village: string | null;
  sugarcane_tons: number | string | null;
  amount_paid: number | string | null;
  payment_pending: number | string | null;
};

const sourceRequired = ["PGHOST", "PGDATABASE", "PGUSER", "PGPASSWORD"] as const;
const missing = sourceRequired.filter(name => !process.env[name]);
if (missing.length) {
  throw new Error(`Set the source database variables in .env before migrating: ${missing.join(", ")}`);
}

const supabaseUrl = process.env.SUPABASE_URL?.replace(/\/$/, "");
const supabaseKey = process.env.SUPABASE_SECRET_KEY || process.env.SUPABASE_SERVICE_ROLE_KEY;
const destinationDatabaseUrl = process.env.DATABASE_URL;
if (!destinationDatabaseUrl && (!supabaseUrl || !supabaseKey)) {
  throw new Error("Set SUPABASE_URL and SUPABASE_SECRET_KEY in .env before migrating.");
}

const host = process.env.PGHOST || "";
const sslDisabled = process.env.PGSSLMODE?.toLowerCase() === "disable";
const sslRequired = process.env.PGSSLMODE?.toLowerCase() === "require"
  || host.endsWith(".supabase.co")
  || host.endsWith(".pooler.supabase.com");
const source = new pg.Pool({
  ssl: sslDisabled ? false : sslRequired ? { rejectUnauthorized: false } : undefined
});
const destination = destinationDatabaseUrl
  ? new pg.Pool({ connectionString: destinationDatabaseUrl, ssl: { rejectUnauthorized: false } })
  : undefined;

function headers(): Record<string, string> {
  const result: Record<string, string> = {
    apikey: supabaseKey!,
    "Content-Type": "application/json",
    Prefer: "resolution=merge-duplicates,return=minimal"
  };
  if (!supabaseKey!.startsWith("sb_secret_")) {
    result.Authorization = `Bearer ${supabaseKey}`;
  }
  return result;
}

async function main() {
  const { rows } = await source.query<FarmerRecord>(`
    SELECT id, name, village, sugarcane_tons, amount_paid, payment_pending
    FROM farmers
    ORDER BY id
  `);
  const batchSize = 200;

  if (destination) {
    await destination.query(`
      CREATE TABLE IF NOT EXISTS public.farmers (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name text NOT NULL,
        village text,
        sugarcane_tons numeric,
        amount_paid numeric,
        payment_pending numeric
      )
    `);
    await destination.query("ALTER TABLE public.farmers ENABLE ROW LEVEL SECURITY");
    await destination.query("GRANT SELECT ON TABLE public.farmers TO service_role");

    for (let offset = 0; offset < rows.length; offset += batchSize) {
      const batch = rows.slice(offset, offset + batchSize);
      const values: Array<string | number | null> = [];
      const tuples = batch.map((row, index) => {
        const base = index * 6;
        values.push(row.id, row.name, row.village, row.sugarcane_tons, row.amount_paid, row.payment_pending);
        return `($${base + 1}, $${base + 2}, $${base + 3}, $${base + 4}, $${base + 5}, $${base + 6})`;
      });
      await destination.query(`
        INSERT INTO public.farmers (id, name, village, sugarcane_tons, amount_paid, payment_pending)
        VALUES ${tuples.join(", ")}
        ON CONFLICT (id) DO UPDATE SET
          name = EXCLUDED.name,
          village = EXCLUDED.village,
          sugarcane_tons = EXCLUDED.sugarcane_tons,
          amount_paid = EXCLUDED.amount_paid,
          payment_pending = EXCLUDED.payment_pending
      `, values);
    }
    await destination.query(`
      SELECT setval(
        pg_get_serial_sequence('public.farmers', 'id'),
        coalesce((select max(id) from public.farmers), 1),
        exists (select 1 from public.farmers)
      )
    `);
    console.log(`Imported ${rows.length} farmer records to Supabase PostgreSQL.`);
    return;
  }

  const endpoint = `${supabaseUrl}/rest/v1/farmers?on_conflict=id`;
  for (let offset = 0; offset < rows.length; offset += batchSize) {
    const batch = rows.slice(offset, offset + batchSize);
    const response = await fetch(endpoint, {
      method: "POST",
      headers: headers(),
      body: JSON.stringify(batch)
    });
    if (!response.ok) {
      const details = await response.text();
      throw new Error(`Supabase import failed with HTTP ${response.status}: ${details}`);
    }
  }

  console.log(`Imported ${rows.length} farmer records to Supabase.`);
  console.log("Run supabase/after-import.sql in the Supabase SQL Editor to sync the ID sequence.");
}

try {
  await main();
} finally {
  await source.end();
  await destination?.end();
}
